const PG_LOWER = new Map<number, number>();
for (let i = 0; i < PG_LOWER_RUNS.length; i += 4) {
  const [first, count, delta, stride] = PG_LOWER_RUNS.slice(i, i + 4);
  for (let k = 0; k < count; k++) PG_LOWER.set(first + k * stride, first + k * stride + delta);
}

const PG_UPPER = new Map<number, number[]>();
for (let code = 65; code <= 90; code++) PG_UPPER.set(code + 32, [code]);
for (const [code, lower] of PG_LOWER) {
  const preimages = PG_UPPER.get(lower);
  if (preimages) preimages.push(code);
  else PG_UPPER.set(lower, [code]);
}

export function pgLowerCodePoint(code: number): number {
  if (code < 128) return code >= 65 && code <= 90 ? code + 32 : code;
  return PG_LOWER.get(code) ?? code;
}

export function pgCaseVariants(code: number): number[] {
  const lower = pgLowerCodePoint(code);
  return [lower, ...(PG_UPPER.get(lower) ?? [])];
}

export function pgLowerText(text: string): string {
  let out = '';
  let last = 0;
  for (const match of text.matchAll(/[^\0-\u007F]+/gu)) {
    out += text.slice(last, match.index).toLowerCase();
    for (const ch of match[0]) out += String.fromCodePoint(pgLowerCodePoint(ch.codePointAt(0)!));
    last = match.index + match[0].length;
  }
  return last === 0 ? text.toLowerCase() : out + text.slice(last).toLowerCase();
}

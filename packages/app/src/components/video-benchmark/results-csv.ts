import type { resultProjection, ResultCell } from './results';

/** One row per selected official or named cell. Values come from the overview projection. */
export function resultCsvRows(projection: ReturnType<typeof resultProjection>) {
  const row = (cell: ResultCell) => {
    const { point, metadata, evidence } = cell;
    return {
      channel: cell.overlay ? 'named' : 'official',
      approved: point.approved ?? false,
      published_at: point.publishedAt ?? null,
      run_id: point.runId,
      artifact_id: point.artifactId,
      source_manifest_sha256: point.id.split(':')[0],
      point_id: point.id,
      cell_id: point.cell,
      workload_key: point.workloadKey ?? null,
      workload_sha256: evidence?.workloadHash ?? null,
      model: metadata.model,
      hardware: point.hardwareKey,
      hardware_name: point.hardwareName,
      engine: metadata.engine,
      mode: metadata.mode,
      resolution: metadata.resolution,
      duration_s: metadata.duration,
      fps: metadata.fps,
      steps: metadata.steps,
      observed_at: point.observedAt,
      participating_gpus: point.participating,
      allocated_gpus: point.allocated,
      scheduled_clips: point.scheduled,
      completed_clips: point.completed,
      valid_clips: point.valid,
      failed_clips: point.failed,
      attempted_clips: evidence?.attempted ?? null,
      warmup_s: evidence?.warmupSeconds ?? null,
      client_p50_s: cell.deliveryP50,
      p95_s: cell.p95,
      clips_per_s: cell.clipsPerSecond,
      deadline_s: projection.state.deadlineSeconds,
      deadline_attainment: cell.deadlineAttainment,
      deadline_goodput_clips_per_s: cell.deadlineGoodput,
      gpu_board_energy_j_per_clip: cell.joulesPerClip,
      gpu_board_mean_w: point.avgPowerW,
      power_valid: evidence?.powerValid ?? null,
      power_samples: evidence?.powerSeries.length ?? null,
      cost_tier: projection.state.costTier,
      participating_cost_usd_per_video: cell.cost.participating?.perVideo ?? null,
      participating_cost_usd_per_video_s: cell.cost.participating?.perVideoSecond ?? null,
      participating_cost_usd_per_hour: cell.cost.participating?.perHour ?? null,
      allocated_cost_usd_per_video: cell.cost.allocated?.perVideo ?? null,
      allocated_cost_usd_per_video_s: cell.cost.allocated?.perVideoSecond ?? null,
      allocated_cost_usd_per_hour: cell.cost.allocated?.perHour ?? null,
      participating_profit_usd_per_hour: cell.profit.participating?.profitPerHour ?? null,
      allocated_profit_usd_per_hour: cell.profit.allocated?.profitPerHour ?? null,
    };
  };
  return [...projection.cells, ...projection.overlayCells].map(row);
}


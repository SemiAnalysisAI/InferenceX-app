const scalar = (token) =>
  token.startsWith('"')
    ? token.slice(1, -1).replaceAll(/\\(?<escaped>["\\])/g, '$<escaped>')
    : token;
// Repeated objects merge; repeated scalars use last-value wins. No game code is imported.
export function parseKeyValues(text) {
  const tokens =
    text
      .match(/"(?:\\.|[^"\\])*"|\/\/[^\n]*|[{}]|[^\s{}"]+/g)
      ?.filter((token) => !token.startsWith('//')) || [];
  let index = 0;
  function object(nested = false) {
    const value = Object.create(null);
    while (index < tokens.length && tokens[index] !== '}') {
      const key = scalar(tokens[index++]);
      const token = tokens[index++];
      if (token === undefined || token === '}') throw new Error(`Missing value for ${key}`);
      value[key] =
        token === '{'
          ? merge(typeof value[key] === 'object' ? value[key] : Object.create(null), object(true))
          : scalar(token);
    }
    if (nested && tokens[index++] !== '}') throw new Error('Unclosed KeyValues object');
    return value;
  }
  const value = object();
  if (index !== tokens.length) throw new Error('Unexpected closing brace');
  return value;
}
function merge(base, next) {
  for (const [key, value] of Object.entries(next)) {
    base[key] =
      typeof value === 'object'
        ? merge(typeof base[key] === 'object' ? base[key] : Object.create(null), value)
        : value;
  }
  return base;
}
export function resolvePrefab(node, prefabs, seen = new Set()) {
  const resolved = Object.create(null);
  for (const name of (node.prefab || '').split(/\s+/).filter(Boolean)) {
    if (seen.has(name) || !prefabs[name]) throw new Error(`Invalid prefab: ${name}`);
    merge(resolved, resolvePrefab(prefabs[name], prefabs, new Set([...seen, name])));
  }
  return merge(resolved, node);
}
export function extractWeapons(bytes) {
  if (createHash('sha256').update(bytes).digest('hex') !== REFERENCE.sha256)
    throw new Error('Weapon reference SHA-256 mismatch');
  const { items_game: schema } = parseKeyValues(bytes.toString('utf8'));
  const weapons = Object.create(null);
  for (const [id, engineId] of Object.entries(IDS)) {
    const item = Object.values(schema.items).find((value) => value.name === `weapon_${engineId}`);
    if (!item) throw new Error(`Missing weapon ${id}`);
    const resolved = resolvePrefab(item, schema.prefabs);
    const attrs = Object.fromEntries(
      Object.entries(resolved.attributes)
        .filter(
          ([, value]) =>
            typeof value === 'string' && value.trim() !== '' && Number.isFinite(Number(value)),
        )
        .map(([key, value]) => [key, Number(value)]),
    );
    for (const key of ['damage', 'cycletime', 'primary clip size', 'range', 'max player speed'])
      if (!(attrs[key] > 0)) throw new Error(`Invalid ${id}: ${key}`);
    weapons[id] = { engineId, attributes: attrs };
  }
  return weapons;
}
if (process.argv[1] === import.meta.filename) {
  if (!process.argv[2]) throw new Error('Pass the downloaded, pinned items_game.txt path');
  const weapons = extractWeapons(await readFile(process.argv[2]));
  await writeFile(
    new URL('weapon-reference.mjs', import.meta.url),
    `// Generated by import-weapon-reference.mjs; do not edit by hand.\nexport const REFERENCE = ${JSON.stringify(REFERENCE, null, 2)};\nexport const WEAPON_REFERENCE = ${JSON.stringify(weapons, null, 2)};\n`,
  );
  console.log(`Extracted ${Object.keys(weapons).length} pinned weapon records`);
}
